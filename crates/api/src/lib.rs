struct Security;

impl utoipa::Modify for Security {
    fn modify(&self, openapi: &mut utoipa::openapi::OpenApi) {
        let components = openapi.components.get_or_insert_with(Default::default);
        components.add_security_scheme(
            "session",
            SecurityScheme::ApiKey(ApiKey::Cookie(ApiKeyValue::with_description(
                SESSION_COOKIE,
                "Session cookie set by login (`solde_session` when the server \
                 runs with SOLDE_INSECURE_COOKIES). State-changing requests must \
                 send `Content-Type: application/json`.",
            ))),
        );
        components.add_security_scheme(
            "bearer",
            SecurityScheme::Http(
                HttpBuilder::new()
                    .scheme(HttpAuthScheme::Bearer)
                    .description(Some("API token from `POST /api/v1/tokens`."))
                    .build(),
            ),
        );
    }
}

/// The OpenAPI document of this API, as pretty-printed JSON with a final
/// newline (the form committed as `apps/web/src/api/openapi.json`).
pub fn openapi_json() -> String {
    match ApiDoc::openapi().to_pretty_json() {
        Ok(mut json) => {
            json.push('\n');
            json
        }
        // Serializing an in-memory document cannot fail in practice.
        Err(err) => format!("{{\"error\": \"{err}\"}}\n"),
    }
}
