/// API settings, from the server's environment.
#[derive(Default)]
pub struct ApiConfig {
    /// Drop `Secure` from the session cookie (and its `__Host-` prefix),
    /// for plain-HTTP LAN setups (`SOLDE_INSECURE_COOKIES=1`). Browsers then
    /// send the cookie over unencrypted connections: avoid outside a
    /// trusted network.
    pub insecure_cookies: bool,
    /// Reverse proxies whose `X-Forwarded-For` is believed
    /// (`SOLDE_TRUSTED_PROXIES`).
    pub trusted_proxies: TrustedProxies,
    /// The one-time code `POST /setup` requires, generated by the server at
    /// startup while the instance is not set up. `None`: setup is refused.
    pub setup_code: Option<SetupCode>,
}

/// The `/api/v1` routes, ready to merge into the server's router. Fails
/// only if the password hasher cannot run: the server must not start then.
///
/// To read client addresses the server must be run with
/// `into_make_service_with_connect_info::<SocketAddr>()`.
pub fn router(store: Arc<dyn Store>, config: ApiConfig) -> Result<Router, InitError> {
    use routes::{accounts, household, session, tokens};

    let api = Router::new()
        .route("/meta", get(session::meta))
        .route("/setup", post(session::setup))
        .route("/auth/login", post(session::login))
        .route("/auth/logout", post(session::logout))
        .route("/me", get(session::me))
        .route("/users", get(household::users))
        .route(
            "/invitations",
            get(household::invitations).post(household::invite),
        )
        .route("/invitations/accept", post(household::accept))
        .route("/accounts", get(accounts::list).post(accounts::create))
        .route(
            "/accounts/{account_id}",
            get(accounts::get).delete(accounts::delete),
        )
        .route("/accounts/{account_id}/access", get(accounts::access))
        .route(
            "/accounts/{account_id}/access/{user_id}",
            put(accounts::grant).delete(accounts::revoke),
        )
        .route(
            "/accounts/{account_id}/transactions",
            get(accounts::transactions).post(accounts::create_transaction_handler),
        )
        .route("/tokens", get(tokens::list).post(tokens::create))
        .route("/tokens/{token_id}", axum::routing::delete(tokens::delete))
        .fallback(not_found)
        .layer(axum::middleware::map_response(api_headers))
        .with_state(AppState::new(store, config)?);
    // Every other `/api` path is a JSON 404 too, so the server's web app
    // fallback never answers API clients with HTML.
    let other = Router::new()
        .route("/api", any(not_found))
        .route("/api/", any(not_found))
        .route("/api/{*rest}", any(not_found))
        .layer(axum::middleware::map_response(api_headers));
    Ok(Router::new().nest("/api/v1", api).merge(other))
}

/// JSON 404 for unknown API paths, like any missing resource.
async fn not_found() -> Response {
    use axum::response::IntoResponse as _;
    error::ApiError::Service(solde_services::ServiceError::NotFound).into_response()
}

/// API answers are private and change often: never cache them. And they
/// are JSON only: browsers must not sniff them into anything else.
async fn api_headers(mut response: Response) -> Response {
    let headers = response.headers_mut();
    headers.insert(header::CACHE_CONTROL, HeaderValue::from_static("no-store"));
    headers.insert(
        header::X_CONTENT_TYPE_OPTIONS,
        HeaderValue::from_static("nosniff"),
    );
    response
}

