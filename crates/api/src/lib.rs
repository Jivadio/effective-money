//! HTTP API under `/api/v1` (Axum), described by an OpenAPI document
//! (utoipa).
//!
//! Must never depend (even transitively) on `solde-secrets` or `solde-sync`.
//!
//! # Authentication
//!
//! - First start: `POST /api/v1/setup` needs the one-time setup code the
//!   server prints in its log while the instance is not set up.
//! - Browser: `POST /api/v1/auth/login` (or setup, or accepting an
//!   invitation) sets the `__Host-solde_session` cookie: `HttpOnly; Secure;
//!   SameSite=Strict; Path=/`, 14 days. It holds a random token; the
//!   database stores only its SHA-256. With `SOLDE_INSECURE_COOKIES=1` the
//!   cookie is `solde_session`, without `Secure`.
//! - Scripts and remote clients: `Authorization: Bearer <token>` with an
//!   API token created from a browser session (`POST /api/v1/tokens`).
//!   Creating tokens and invitations needs a browser session.
//! - Passwords: Argon2id (m = 19 MiB, t = 2, p = 1); unknown emails verify
//!   against a dummy hash so they cannot be told apart by timing. At most
//!   twice the CPU count hash at once; more answer 429.
//! - Login, setup and invitation acceptance: 5 attempts per minute and
//!   client (IPv4 address or IPv6 /64), 60 per minute in total.
//!   `X-Forwarded-For` is read only from trusted proxies.
//! - CSRF: see the `auth` module: `SameSite=Strict`, plus
//!   `Content-Type: application/json` required on state-changing
//!   cookie-authenticated requests.
//!
//! Errors are JSON `{ "code", "message" }` with a stable `code`; they never
//! contain personal data. Every answer carries `Cache-Control: no-store`
//! and `X-Content-Type-Options: nosniff`.

