//! The [`Store`] trait: every query Solde runs, behind one interface.
//!
//! The store does not decide visibility: it returns what it is asked for,
//! and `services` filters through `visible_account_ids(viewer)` (built on
//! [`solde_core_domain::permission_on`]). Methods listing household data
//! therefore take a household id, never a viewer.

use async_trait::async_trait;
use solde_core_domain::{
    Account, AccountAccess, AccountId, Household, HouseholdId, Transaction, TransactionId, User,
    UserId,
};

use crate::StoreError;
use crate::model::{
    ApiToken, ApiTokenId, Invitation, NewAccount, NewApiToken, NewInvitation, NewMember,
    NewSession, NewTransaction, NewUser, Session, Timestamp, UserCredentials,
};

/// Which database a [`Store`] talks to.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Backend {
    Postgres,
    Sqlite,
}

/// Persistence for the household, its members, access, accounts and manual
/// transactions. Implemented once for both backends by
/// [`SqlStore`](crate::SqlStore).
///
/// Ids are UUIDv7 generated by the store. Creation timestamps are taken
/// from the system clock; every expiry check takes `now` from the caller.
#[async_trait]
pub trait Store: Send + Sync {
    /// The database this store talks to.
    fn backend(&self) -> Backend;

    /// Highest migration applied to the database.
    async fn schema_version(&self) -> Result<i64, StoreError>;

    // --- Households and members ---------------------------------------

    /// Creates the household and its first member, an
    /// [`Admin`](solde_core_domain::Role::Admin), once per instance.
    /// [`StoreError::Conflict`] when a household already exists. Atomic: two
    /// concurrent calls never create two households.
    async fn bootstrap(
        &self,
        household_name: &str,
        admin: NewMember,
    ) -> Result<(Household, User), StoreError>;

    /// Whether [`Store::bootstrap`] already ran.
    async fn is_bootstrapped(&self) -> Result<bool, StoreError>;

    async fn get_household(&self, id: HouseholdId) -> Result<Option<Household>, StoreError>;

    /// Adds a member. [`StoreError::Conflict`] on a taken email,
    /// [`StoreError::MissingReference`] on an unknown household.
    async fn create_user(&self, user: NewUser) -> Result<User, StoreError>;

    async fn get_user(&self, id: UserId) -> Result<Option<User>, StoreError>;

    /// Members of a household, oldest first.
    async fn list_users(&self, household_id: HouseholdId) -> Result<Vec<User>, StoreError>;

    /// Login data for an (already normalized) email.
    async fn find_credentials(&self, email: &str) -> Result<Option<UserCredentials>, StoreError>;

    /// Replaces a member's password hash. [`StoreError::NotFound`] for an
    /// unknown member.
    async fn set_password_hash(&self, id: UserId, password_hash: &str) -> Result<(), StoreError>;

    // --- Sessions ------------------------------------------------------

    async fn create_session(&self, session: NewSession) -> Result<Session, StoreError>;

    /// The session with this token hash, unless it expired at `now`.
    async fn find_session(
        &self,
        token_hash: &str,
        now: Timestamp,
    ) -> Result<Option<Session>, StoreError>;

    /// Logs out. Returns whether a session was deleted.
    async fn delete_session(&self, token_hash: &str) -> Result<bool, StoreError>;

    /// Deletes every session expired at `now`; returns how many.
    async fn delete_expired_sessions(&self, now: Timestamp) -> Result<u64, StoreError>;

    // --- API tokens ----------------------------------------------------

    async fn create_api_token(&self, token: NewApiToken) -> Result<ApiToken, StoreError>;

    /// The token with this hash, unless it expired at `now`.
    async fn find_api_token(
        &self,
        token_hash: &str,
        now: Timestamp,
    ) -> Result<Option<ApiToken>, StoreError>;

    /// A member's tokens, oldest first.
    async fn list_api_tokens(&self, user_id: UserId) -> Result<Vec<ApiToken>, StoreError>;

    /// Records a use of the token. [`StoreError::NotFound`] if it is gone.
    async fn touch_api_token(&self, id: ApiTokenId, now: Timestamp) -> Result<(), StoreError>;

    /// Revokes one of `user_id`'s tokens. Returns whether one was deleted
    /// (a token of another member is never touched).
    async fn delete_api_token(&self, user_id: UserId, id: ApiTokenId) -> Result<bool, StoreError>;

    // --- Invitations ---------------------------------------------------

    async fn create_invitation(&self, invitation: NewInvitation) -> Result<Invitation, StoreError>;

    /// The pending invitation with this hash: not accepted and not expired
    /// at `now`.
    async fn find_invitation(
        &self,
        token_hash: &str,
        now: Timestamp,
    ) -> Result<Option<Invitation>, StoreError>;

    /// Invitations of a household, newest first.
    async fn list_invitations(
        &self,
        household_id: HouseholdId,
    ) -> Result<Vec<Invitation>, StoreError>;

    /// Consumes a pending invitation and creates the member, atomically.
    /// [`StoreError::NotFound`] when the invitation is unknown, expired or
    /// already used; [`StoreError::Conflict`] on a taken email (the
    /// invitation then stays pending).
    async fn accept_invitation(
        &self,
        token_hash: &str,
        member: NewMember,
        now: Timestamp,
    ) -> Result<User, StoreError>;

    // --- Accounts and access -----------------------------------------

    /// Creates a manual account and makes `owner` its
    /// [`Owner`](solde_core_domain::Permission::Owner), atomically. IBANs
    /// are not unique here: duplicates are refused in services, among the
    /// accounts the creator can see.
    async fn create_account(
        &self,
        account: NewAccount,
        owner: UserId,
    ) -> Result<Account, StoreError>;

    async fn get_account(&self, id: AccountId) -> Result<Option<Account>, StoreError>;

    /// Every account of the household, visible or not: filter through
    /// `visible_account_ids` before showing anything.
    async fn list_accounts(&self, household_id: HouseholdId) -> Result<Vec<Account>, StoreError>;

    /// Deletes an account with its access grants and transactions. Returns
    /// whether it existed.
    async fn delete_account(&self, id: AccountId) -> Result<bool, StoreError>;

    /// Every access grant in the household: the input of
    /// [`solde_core_domain::permission_on`].
    async fn list_household_access(
        &self,
        household_id: HouseholdId,
    ) -> Result<Vec<AccountAccess>, StoreError>;

    /// Grants on one account.
    async fn list_account_access(
        &self,
        account_id: AccountId,
    ) -> Result<Vec<AccountAccess>, StoreError>;

    /// Grants or changes one member's permission on one account (one grant
    /// per pair). [`StoreError::MissingReference`] for an unknown account
    /// or member; [`StoreError::LastOwner`] (and no change) when it would
    /// demote the account's only owner. The check and the write happen in
    /// one serialized transaction, so concurrent calls can never leave an
    /// account without an owner.
    async fn set_account_access(&self, access: AccountAccess) -> Result<(), StoreError>;

    /// Removes a member's grant. Returns whether one existed.
    /// [`StoreError::LastOwner`] (and no change) when it is the account's
    /// only owner; atomic like [`Store::set_account_access`].
    async fn revoke_account_access(
        &self,
        account_id: AccountId,
        user_id: UserId,
    ) -> Result<bool, StoreError>;

    // --- Transactions ------------------------------------------------

    /// Records a manual transaction. [`StoreError::DateOutOfRange`] outside
    /// years 0000-9999 (Q-DATE), [`StoreError::MissingReference`] for an
    /// unknown account.
    async fn create_transaction(
        &self,
        transaction: NewTransaction,
    ) -> Result<Transaction, StoreError>;

    async fn get_transaction(&self, id: TransactionId) -> Result<Option<Transaction>, StoreError>;

    /// The `limit` most recent transactions of an account, newest booking
    /// date first.
    async fn list_transactions(
        &self,
        account_id: AccountId,
        limit: u32,
    ) -> Result<Vec<Transaction>, StoreError>;
}
